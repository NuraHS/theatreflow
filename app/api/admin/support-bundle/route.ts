import JSZip from "jszip";
import { NextResponse } from "next/server";
import {
  getKnownSchemaMigrations,
  getSystemHealthSnapshots,
  getSystemIncidents,
  getSystemMaintenanceEvents
} from "@/lib/repositories/system-repository";
import { hasPermission, isRolePermissionEnforced } from "@/lib/services/access-control";
import { supportHealth, supportIncidents, supportHistory, supportMaintenance, supportMigrations } from "@/lib/services/support-bundle-data";
import { getSystemHealthReport } from "@/lib/services/system-health";

export const dynamic = "force-dynamic";

export async function GET() {
  if (!(await hasPermission("viewSystemDiagnostics"))) return NextResponse.json({ error: "Administrator access is required." }, { status: 403 });

  const health = await getSystemHealthReport();
  const collections = await Promise.allSettled([
    getSystemIncidents(500, true), getSystemHealthSnapshots(500, true),
    getSystemMaintenanceEvents(500, true), getKnownSchemaMigrations(true)
  ]);
  const [incidents, snapshots, maintenance, migrations] = collections;
  const collectionStatus = Object.fromEntries(["incidents", "snapshots", "maintenance", "migrations"].map((name, index) => [name, collections[index].status === "fulfilled" ? "collected" : "unavailable"]));
  const generatedAt = new Date();
  const zip = new JSZip();
  zip.file("README.txt", [
    "Theatreflow structured technical support bundle",
    "",
    "This bundle was generated by the installation and contains structured health, incident, maintenance and migration metadata.",
    "It does not query or export patients, workflow events, procedures, hospital numbers or the clinical audit log.",
    "Free-text incident descriptions, maintenance notes, user identities and historical details JSON are excluded. Review the bundle before sharing. Collection failures are explicitly marked in the manifest; they are not empty histories.",
    "",
    `Generated: ${generatedAt.toISOString()}`
  ].join("\n"));
  zip.file("manifest.json", json({
    bundle_format: "theatreflow-support-bundle-v2",
    generated_at: generatedAt.toISOString(),
    patient_data_included: false,
    free_text_included: false,
    collection_status: collectionStatus,
    history_limit_per_collection: 500,
    ordering: "newest first",
    files: ["health.json", "technical-incidents.json", "health-history.json", "maintenance-history.json", "migration-status.json", "safe-configuration.json"]
  }));
  zip.file("health.json", json(supportHealth(health)));
  zip.file("technical-incidents.json", json(incidents.status === "fulfilled" ? supportIncidents(incidents.value) : { collection_status: "unavailable" }));
  zip.file("health-history.json", json(snapshots.status === "fulfilled" ? supportHistory(snapshots.value) : { collection_status: "unavailable" }));
  zip.file("maintenance-history.json", json(maintenance.status === "fulfilled" ? supportMaintenance(maintenance.value) : { collection_status: "unavailable" }));
  zip.file("migration-status.json", json(migrations.status === "fulfilled" ? supportMigrations(migrations.value) : { collection_status: "unavailable" }));
  zip.file("safe-configuration.json", json({
    deployment_mode: health.deployment_mode === "Cloud hosting / Supabase" ? "cloud" : "local",
    node_environment: process.env.NODE_ENV,
    database_configured: Boolean(process.env.NEXT_PUBLIC_SUPABASE_URL),
    service_role_configured: Boolean(process.env.SUPABASE_SERVICE_ROLE_KEY),
    storage_path_configured: Boolean(process.env.THEATREFLOW_STORAGE_PATH),
    certificate_expiry_configured: Boolean(process.env.THEATREFLOW_CERTIFICATE_EXPIRES_AT),
    role_permissions_enforced: isRolePermissionEnforced(),
    automatic_support_upload_enabled: false
  }));

  const archive = await zip.generateAsync({ type: "uint8array", compression: "DEFLATE", compressionOptions: { level: 6 } });
  const responseBody = new Uint8Array(archive).buffer as ArrayBuffer;
  const date = generatedAt.toISOString().slice(0, 10);
  return new NextResponse(responseBody, {
    headers: {
      "Content-Type": "application/zip",
      "Content-Disposition": `attachment; filename="theatreflow-support-${date}.zip"`,
      "Cache-Control": "no-store",
      "X-Content-Type-Options": "nosniff"
    }
  });
}

function json(value: unknown) {
  return JSON.stringify(value, null, 2);
}
